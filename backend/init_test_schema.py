
import os
from pathlib import Path

import psycopg
from dotenv import dotenv_values

BASE_DIR = Path(__file__).resolve().parent
TEST_ENV = BASE_DIR / ".env.test"

config = dotenv_values(TEST_ENV)

required = ["PGHOST", "PGDATABASE", "PGUSER", "PGPASSWORD"]
missing = [key for key in required if not config.get(key)]

if missing:
    raise SystemExit(
        "Missing settings in backend/.env.test: "
        + ", ".join(missing)
    )

# Refuse to proceed unless the database has an explicit test marker.
if os.getenv("ALLOW_TEST_SCHEMA_INIT") != "YES":
    raise SystemExit(
        "Safety check: set ALLOW_TEST_SCHEMA_INIT=YES "
        "after confirming this is the test database."
    )

with psycopg.connect(
    host=config["PGHOST"],
    port=int(config.get("PGPORT") or "5432"),
    dbname=config["PGDATABASE"],
    user=config["PGUSER"],
    password=config["PGPASSWORD"],
    connect_timeout=10,
    sslmode="require",
) as connection:
    with connection.cursor() as cursor:
        cursor.execute(
            "SELECT current_database(), current_user, "
            "current_schema(), inet_server_addr()::text"
        )
        database, user, schema, server = cursor.fetchone()

        print("Connected database:", database)
        print("Database role:", user)
        print("Schema:", schema)
        print("Server address:", server)

        # Confirm the test project before any schema changes.
        confirmation = input(
            "Type CREATE TEST SCHEMA to continue: "
        ).strip()

        if confirmation != "CREATE TEST SCHEMA":
            raise SystemExit("Cancelled; no schema changes made.")

        cursor.execute("CREATE EXTENSION IF NOT EXISTS vector")

        cursor.execute("""
            CREATE TABLE IF NOT EXISTS public.documents (
                id TEXT PRIMARY KEY,
                filename TEXT NOT NULL,
                file_type TEXT NOT NULL,
                size_bytes BIGINT NOT NULL,
                extracted_text TEXT NOT NULL,
                created_at TIMESTAMPTZ NOT NULL,
                indexing_status TEXT NOT NULL DEFAULT 'pending'
            )
        """)

        cursor.execute("""
            CREATE TABLE IF NOT EXISTS public.document_chunks (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                document_id TEXT NOT NULL,
                filename TEXT NOT NULL,
                chunk_index INTEGER NOT NULL,
                chunk_text TEXT NOT NULL,
                embedding vector(384),
                created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                UNIQUE (document_id, chunk_index)
            )
        """)

        cursor.execute("""
            CREATE INDEX IF NOT EXISTS
            idx_test_document_chunks_document_id
            ON public.document_chunks (document_id)
        """)

        cursor.execute("""
            CREATE INDEX IF NOT EXISTS
            idx_test_document_chunks_embedding
            ON public.document_chunks
            USING hnsw (embedding vector_cosine_ops)
            WHERE embedding IS NOT NULL
        """)

    connection.commit()

print("Test schema initialization completed.")
